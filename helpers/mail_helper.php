<?php

require_once __DIR__ . '/../vendor/autoload.php';

use Dotenv\Dotenv;
use PHPMailer\PHPMailer\PHPMailer;
use PHPMailer\PHPMailer\Exception;

$dotenv = Dotenv::createImmutable(dirname(__DIR__));
$dotenv->safeLoad();

class MailHelper
{
    public static function sendAdminOrderNotification($orderId, $customer, $items, $totalAmount)
    {
        $username    = $_ENV['USERNAME']    ?? '';
        $password    = $_ENV['PASSWORD']    ?? '';
        $admin_gmail = $_ENV['ADMIN_GMAIL'] ?? '';

        if (!$username || !$password) {
            throw new Exception("Mail configuration missing — add USERNAME, PASSWORD, ADMIN_GMAIL to api/.env");
        }

        $mail = new PHPMailer(true);

        try {
            $mail->isSMTP();
            $mail->Host       = 'smtp.gmail.com';
            $mail->SMTPAuth   = true;
            $mail->Username   = $username;
            $mail->Password   = $password;
            $mail->SMTPSecure = PHPMailer::ENCRYPTION_STARTTLS;
            $mail->Port       = 587;

            $mail->setFrom($username, 'Manoharam Real Foods');
            $mail->addAddress($admin_gmail);
            $mail->isHTML(true);
            $mail->Subject = "🛒 New Order Received #{$orderId}";

            $rows = '';
            foreach ($items as $item) {
                $lineTotal = $item['quantity'] * $item['selling_price'];
                $rows .= "
                <tr>
                  <td style='padding:12px;border:1px solid #ddd;'>{$item['name']}</td>
                  <td style='padding:12px;border:1px solid #ddd;text-align:center;'>{$item['quantity']}</td>
                  <td style='padding:12px;border:1px solid #ddd;text-align:right;'>₹" . number_format($item['selling_price'], 2) . "</td>
                  <td style='padding:12px;border:1px solid #ddd;text-align:right;'>₹" . number_format($lineTotal, 2) . "</td>
                </tr>";
            }

            $mail->Body = "
            <!DOCTYPE html><html><head><meta charset='UTF-8'></head>
            <body style='font-family:Arial,sans-serif;background:#f5f5f5;padding:20px;'>
            <div style='max-width:800px;margin:auto;background:#fff;border-radius:12px;overflow:hidden;box-shadow:0 2px 12px rgba(0,0,0,.1);'>
              <div style='background:#C1272D;color:white;padding:20px;text-align:center;'>
                <h1 style='margin:0;'>🛒 New Order Received</h1>
                <p style='margin-top:8px;'>Manoharam Real Foods</p>
              </div>
              <div style='padding:20px;'>
                <h2 style='color:#C1272D;'>Order Details</h2>
                <p><strong>Order ID:</strong> #{$orderId}</p>
                <p><strong>Customer:</strong> {$customer['name']}</p>
                <p><strong>Email:</strong> {$customer['email']}</p>
                <p><strong>Phone:</strong> {$customer['phone']}</p>
                <hr style='margin:20px 0;'>
                <h2 style='color:#C1272D;'>Products</h2>
                <table style='width:100%;border-collapse:collapse;margin-top:15px;'>
                  <thead>
                    <tr style='background:#C1272D;color:white;'>
                      <th style='padding:12px;border:1px solid #ddd;'>Product</th>
                      <th style='padding:12px;border:1px solid #ddd;'>Qty</th>
                      <th style='padding:12px;border:1px solid #ddd;'>Unit Price</th>
                      <th style='padding:12px;border:1px solid #ddd;'>Total</th>
                    </tr>
                  </thead>
                  <tbody>{$rows}</tbody>
                </table>
                <div style='margin-top:20px;padding:15px;background:#FDECEC;border-left:5px solid #C1272D;border-radius:6px;'>
                  <h2 style='margin:0;color:#C1272D;'>Grand Total: ₹" . number_format($totalAmount, 2) . "</h2>
                </div>
              </div>
              <div style='background:#fafafa;padding:15px;text-align:center;color:#666;border-top:1px solid #eee;'>
                Automatically generated by <strong>Manoharam Real Foods</strong>
              </div>
            </div>
            </body></html>";

            $mail->send();
            return true;

        } catch (Exception $e) {
            error_log("Order mail error: " . $mail->ErrorInfo);
            throw $e; // re-throw so caller can catch and log without exposing to customer
        }
    }

