    public static function sendAdminLowStockNotification($products, $threshold)
    {
        $username    = $_ENV['USERNAME']    ?? '';
        $password    = $_ENV['PASSWORD']    ?? '';
        $admin_gmail = $_ENV['ADMIN_GMAIL'] ?? '';

        if (!$username || !$password || !$admin_gmail) {
            throw new Exception(
                "Mail configuration missing — add USERNAME, PASSWORD, ADMIN_GMAIL to api/.env"
            );
        }

        if (empty($products)) {
            return true;
        }

        $mail = new PHPMailer(true);

        try {

            $mail->isSMTP();
            $mail->Host       = 'smtp.gmail.com';
            $mail->SMTPAuth   = true;
            $mail->Username   = $username;
            $mail->Password   = $password;
            $mail->SMTPSecure = PHPMailer::ENCRYPTION_STARTTLS;
            $mail->Port       = 587;

            $mail->setFrom($username, 'Manoharam Real Foods');
            $mail->addAddress($admin_gmail);

            $mail->isHTML(true);
            $mail->Subject = "⚠️ Low Stock Alert - Manoharam Real Foods";

            $rows = '';

            foreach ($products as $product) {

                $remaining = (float)$product['remaining_quantity'];

                $rows .= "
                    <tr>
                        <td style='padding:12px;border:1px solid #ddd;'>
                            " . htmlspecialchars($product['name']) . "
                        </td>

                        <td style='padding:12px;border:1px solid #ddd;text-align:center;'>
                            " . htmlspecialchars($product['product_quantity']) . "
                            " . htmlspecialchars($product['product_unit']) . "
                        </td>

                        <td style='padding:12px;border:1px solid #ddd;text-align:center;font-weight:bold;color:#C1272D;'>
                            " . number_format($remaining, 2) . "
                        </td>
                    </tr>";
            }

            $mail->Body = "
            <!DOCTYPE html>
            <html>
            <head>
                <meta charset='UTF-8'>
            </head>

            <body style='font-family:Arial,sans-serif;background:#f5f5f5;padding:20px;'>

            <div style='max-width:800px;margin:auto;background:#fff;border-radius:12px;overflow:hidden;box-shadow:0 2px 12px rgba(0,0,0,.1);'>

                <div style='background:#C1272D;color:white;padding:20px;text-align:center;'>
                    <h1 style='margin:0;'>⚠️ Low Stock Alert</h1>
                    <p style='margin-top:8px;'>Manoharam Real Foods</p>
                </div>

                <div style='padding:20px;'>

                    <h2 style='color:#C1272D;'>Inventory Alert</h2>

                    <p>
                        The following active products have reached or fallen below
                        the low-stock threshold of
                        <strong>" . number_format($threshold, 2) . "</strong>.
                    </p>

                    <table style='width:100%;border-collapse:collapse;margin-top:20px;'>

                        <thead>
                            <tr style='background:#C1272D;color:white;'>

                                <th style='padding:12px;border:1px solid #ddd;'>
                                    Product
                                </th>

                                <th style='padding:12px;border:1px solid #ddd;'>
                                    Product Size
                                </th>

                                <th style='padding:12px;border:1px solid #ddd;'>
                                    Remaining Stock
                                </th>

                            </tr>
                        </thead>

                        <tbody>
                            {$rows}
                        </tbody>

                    </table>

                    <div style='margin-top:20px;padding:15px;background:#FDECEC;border-left:5px solid #C1272D;border-radius:6px;'>

                        <strong>
                            Please check the inventory and add new stock if required.
                        </strong>

                    </div>

                </div>

                <div style='background:#fafafa;padding:15px;text-align:center;color:#666;border-top:1px solid #eee;'>
                    Automatically generated by <strong>Manoharam Real Foods</strong>
                </div>

            </div>

            </body>
            </html>";

            $mail->send();

            return true;

        } catch (Exception $e) {

            error_log(
                "Low stock mail error: " . $mail->ErrorInfo
            );

            throw $e;
        }
    }
}
